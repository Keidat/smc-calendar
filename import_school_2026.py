def rows():
    result=[]
    for dates,title,description in SCHEDULE:
        for date in dates.split(','):
            dt.date.fromisoformat(date)
            result.append({'date':date,'title':title,'description':description,'scope':'school'})
    return result

def run():
    server.init()
    added=0
    with server.connect() as db:
        admin=db.execute("SELECT id FROM users WHERE role='admin' ORDER BY id LIMIT 1").fetchone()
        for event in rows():
            existing=db.execute("SELECT id FROM events WHERE scope='school' AND date=? AND title=?",(event['date'],event['title'])).fetchone()
            if existing: continue
            description=event['description']
            db.execute('INSERT INTO events(title,date,description,scope,class_name,author) VALUES(?,?,?,?,?,?)',(event['title'],event['date'],description.strip(),'school',None,admin['id'] if admin else None))
            added+=1
    folder=Path(__file__).parent/'data';folder.mkdir(exist_ok=True)
    (folder/'school-2026.json').write_text(json.dumps({'source':SOURCE,'events':rows()},ensure_ascii=False,indent=2),'utf-8')
    print(json.dumps({'added':added,'source_events':len(rows()),'first':'2026-03-02','last':'2027-01-11'}))

if __name__=='__main__':run()
